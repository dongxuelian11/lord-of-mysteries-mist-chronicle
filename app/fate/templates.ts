const SUCCESS_SIDE: ResultLevel[] = ["critical-success", "success", "partial-success"];
const FAILURE_SIDE: ResultLevel[] = ["failure", "fail-with-progress", "backlash"];

type TemplateInput = Omit<FateAberrationTemplate, "sourceType">;

function tpl(input: TemplateInput): FateAberrationTemplate {
  return { sourceType: "game-original-fate-template", ...input };
}

function worldEvent(title: string, detail: string, visibility: WorldEventProposal["visibility"] = "world"): WorldEventProposal {
  return { type: "fate-aberration", title, detail, participantIds: [], observerIds: [], visibility };
}

function belief(input: Omit<CharacterBeliefProposal, "claimType" | "truthStatus" | "confidence"> & Partial<Pick<CharacterBeliefProposal, "claimType" | "truthStatus" | "confidence">>): CharacterBeliefProposal {
  return { claimType: "report", truthStatus: "uncertain", confidence: 0.8, ...input };
}

function relationship(input: RelationshipChangeProposal): RelationshipChangeProposal {
  return input;
}

function commitment(input: CommitmentProposal): CommitmentProposal {
  return input;
}

function plan(input: ActivePlanProposal): ActivePlanProposal {
  return input;
}

function hook(input: FateRecoveryHook): FateRecoveryHook {
  return input;
}

function effect(kind: FateImmediateEffect["kind"], description: string, targetId?: string): FateImmediateEffect {
  return { kind, description, targetId };
}

function delayed(id: string, inWeeks: number, kind: TemplateDelayedEffect["kind"], description: string, worldEventTitle: string): TemplateDelayedEffect {
  return { id, inWeeks, kind, description, worldEventTitle };
}

function cond(kind: FateCondition["kind"], min?: number, max?: number): FateCondition {
  return { kind, min, max };
}

