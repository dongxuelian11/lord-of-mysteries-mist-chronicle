export function safeFallbackFor(twist: FateTwist): FateAberrationTemplate {
  const map: Record<FateTwist, FateAberrationTemplate | undefined> = {
    pure: SAFE_FALLBACK_TEMPLATES.find((item) => item.id === "fate-safe-fallback-pure"),
    "cursed-boon": SAFE_FALLBACK_TEMPLATES.find((item) => item.id === "fate-safe-fallback-cursed-boon"),
    "fortunate-disaster": SAFE_FALLBACK_TEMPLATES.find((item) => item.id === "fate-safe-fallback-fortunate-disaster"),
    "full-disaster": SAFE_FALLBACK_TEMPLATES.find((item) => item.id === "fate-safe-fallback-full-disaster"),
  };
  const template = map[twist];
  if (!template) throw new Error(`缺少安全兜底模板：${twist}`);
  return template;
}
